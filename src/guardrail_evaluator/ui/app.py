def sample_path(choice):
    filename = "demo_scenarios.jsonl" if choice == "Guided demo scenarios · 7" else "paired_scenarios.jsonl"
    return Path(str(files("guardrail_evaluator").joinpath("data", filename)))


def download_copies(paths):
    """Serve only explicit report copies from the private cache, not arbitrary storage roots."""
    cache = Path(tempfile.mkdtemp(prefix="reports-", dir=os.environ.get("GRADIO_TEMP_DIR")))
    copies = []
    for path in paths:
        target = cache / Path(path).name
        shutil.copyfile(path, target)
        target.chmod(0o600)
        copies.append(str(target))
    return copies


def load_mapped(path, mode, values, max_bytes=10 * 1024 * 1024):
    data = load_dataset(path, mode, max_bytes=max_bytes)
    if all(v == "Auto" for v in values):
        return data
    overrides = {
        k: None if v in ("None", None) else v
        for k, v in zip(("input", "output", "input_label", "output_label"), values)
        if v != "Auto"
    }
    mapping = ColumnMapping(**{**data.mapping.model_dump(), **overrides})
    return load_dataset(path, mode, mapping, max_bytes)


