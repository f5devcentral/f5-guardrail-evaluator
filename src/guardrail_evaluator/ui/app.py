        async def run_evaluation(
            file,
            selected,
            selected_mode,
            selected_source,
            selected_project,
            workers,
            selected_strategy,
            allow_invalid,
            cfg,
            opts,
            cancel,
            input_col,
            output_col,
            input_label,
            output_label,
            kind=None,
            progress=gr.Progress(),  # noqa: B008 — Gradio injects this progress object
        ):
            values = (input_col, output_col, input_label, output_label)
            try:
                if kind == "Upload a file" and not file:
                    raise gr.Error("Choose a CSV or JSONL file before starting.")
                effective_file = None if kind == "Sample library" else file
                data = load_mapped(
                    effective_file or sample_path(selected), selected_mode, values, cfg.max_file_bytes
                )
                if data.errors and not allow_invalid:
                    raise gr.Error(
                        "Dataset contains invalid rows. Preview the errors, fix them or explicitly enable continuing with valid rows."
                    )
                if not data.scenarios:
                    raise gr.Error("No valid scenarios. Preview the dataset and check the column mapping.")
                cfg = Settings(
                    **{
                        **cfg.snapshot(),
                        "token": cfg.token,
                        "project": selected_project or "",
                        "concurrency": int(workers),
                    }
                )
                client = DemoClient() if selected_source == "Demo Data Mode" else F5Client(cfg, options=opts)
                async with client:
                    run = await evaluate(
                        data,
                        client,
                        selected_mode,
                        selected_strategy,
                        concurrency=int(workers),
                        cancel=cancel,
                        config={
                            **cfg.snapshot(),
                            "scan_options": opts.model_dump(),
                            "mapping": data.mapping.model_dump(),
                            "invalid_rows": data.errors,
                        },
                        progress=lambda n, total, r: progress(n / total, desc=f"{n}/{total} · {r.status}"),
                    )
                summary = summarize(run)
                cards = metric_cards(run, summary)
                persistence_note = ""
                paths = []
                if cfg.persist:
                    try:
                        paths = download_copies(export_run(run, cfg.result_dir))
                    except OSError:
                        persistence_note = " · Report storage failed; results remain available in memory."
                return (
                    run,
                    f"**{ {'completed': 'Evaluation complete', 'completed_with_errors': 'Finished with errors', 'cancelled': 'Run cancelled'}.get(run.status, run.status) }**{persistence_note}",
                    completion_summary(run),
                    result_frame(run),
                    cards,
                    decision_chart(summary),
                    latency_chart(run),
                    summary,
                    compact_results(result_frame(run)),
                    gr.update(choices=[r.scenario.id for r in run.results], value=None),
                    paths,
                    metric_frame(summary),
                    scanner_frame(summary),
                    category_frame(summary),
                )
            except gr.Error:
                raise
            except (ValueError, OSError, APIError):
                raise gr.Error(
                    "Evaluation could not start or save reports. Check dataset mapping, token, numeric settings and result-folder permissions."
                ) from None

